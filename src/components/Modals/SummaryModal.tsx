import React, { useState } from 'react';
import { X, FileText, Copy, Check, Send, Sparkles } from 'lucide-react';
import { FormattedMessage } from '../../utils/markdown';

interface SummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  roomName: string;
  summaryText: string;
  isLoading: boolean;
  onPostToChannel: (summaryText: string) => void;
}

export const SummaryModal: React.FC<SummaryModalProps> = ({
  isOpen,
  onClose,
  roomName,
  summaryText,
  isLoading,
  onPostToChannel,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(summaryText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePost = () => {
    onPostToChannel(`📝 **Channel Discussion Recap:**\n\n${summaryText}`);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-fadeIn">
      <div className="w-full max-w-xl bg-slate-900 border border-slate-800 rounded-2xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh]">
        {/* Header */}
        <div className="px-5 py-4 border-b border-slate-800 flex items-center justify-between shrink-0">
          <div className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-indigo-600/20 text-indigo-400 flex items-center justify-center">
              <Sparkles className="w-4 h-4" />
            </div>
            <div>
              <h2 className="font-semibold text-sm text-white">
                Channel Discussion Recap
              </h2>
              <p className="text-[11px] text-slate-400">Generated by Gemini for #{roomName}</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Content */}
        <div className="p-5 overflow-y-auto flex-1">
          {isLoading ? (
            <div className="py-12 flex flex-col items-center justify-center gap-3 text-center">
              <div className="w-8 h-8 rounded-full border-2 border-indigo-500 border-t-transparent animate-spin" />
              <p className="text-xs text-slate-300">
                Gemini is synthesizing key discussions between members and AI bots...
              </p>
            </div>
          ) : (
            <div className="bg-slate-950/70 border border-slate-800/80 rounded-xl p-4 text-slate-200">
              <FormattedMessage content={summaryText} />
            </div>
          )}
        </div>

        {/* Footer Actions */}
        {!isLoading && (
          <div className="px-5 py-3 border-t border-slate-800 flex items-center justify-between shrink-0 bg-slate-950/40">
            <button
              onClick={handleCopy}
              className="px-3 py-1.5 rounded-lg text-xs font-medium text-slate-300 hover:text-white hover:bg-slate-800 border border-slate-700/80 flex items-center gap-1.5 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Recap'}</span>
            </button>

            <div className="flex items-center gap-2">
              <button
                onClick={onClose}
                className="px-3.5 py-1.5 rounded-lg text-xs font-medium text-slate-400 hover:text-white transition-colors"
              >
                Close
              </button>
              <button
                onClick={handlePost}
                className="px-4 py-1.5 rounded-lg text-xs font-semibold bg-indigo-600 hover:bg-indigo-500 text-white flex items-center gap-1.5 transition-colors shadow-md shadow-indigo-600/20"
              >
                <Send className="w-3.5 h-3.5" />
                <span>Post in #{roomName}</span>
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
